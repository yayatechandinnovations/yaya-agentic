-- Platform foundation for yaya-identity (milestone I0).
--
-- Everything lives in the yaya_identity schema. There are NO cross-schema
-- references anywhere in this file — table names are unqualified and land in
-- the Flyway default schema (yaya_identity). SchemaIsolationLintTest fails the
-- build if any migration references a foreign schema, so this service can be
-- lifted to its own Postgres instance without a migration (design §14, PRD
-- FR-7.2 / AC-41; mirrors the yaya-sales S0 isolation guard).

-- Signing keys: RS256 key material for token issuance / JWKS. The private key
-- is stored as an AES-256-GCM envelope (ciphertext + fresh IV), never plaintext.
-- Rotated keys are RETIRING (still in JWKS so in-flight tokens verify) then RETIRED.
create table signing_keys (
    kid          varchar(128) primary key,
    alg          varchar(16)  not null,
    public_pem   text         not null,
    private_ct   text         not null,     -- AES-256-GCM ciphertext (base64) of the PKCS#8 private key
    private_iv   text         not null,     -- 12-byte GCM IV (base64); fresh per row, never reused
    status       varchar(16)  not null,
    created_at   timestamptz  not null default now(),
    retiring_at  timestamptz,
    constraint signing_keys_alg_ck    check (alg = 'RS256'),
    constraint signing_keys_status_ck check (status in ('ACTIVE', 'RETIRING', 'RETIRED'))
);
create index signing_keys_status_idx on signing_keys (status);

-- Append-only audit of every auth event and authorization decision. A DENY
-- carries TWO distinct reasons (non-negotiable #3): user_reason (may be shown)
-- and audit_reason (internal truth). Immutability is enforced by a trigger so
-- even the schema owner cannot rewrite history.
create table audit_log (
    id           bigint generated by default as identity primary key,
    org_id       varchar(64),
    actor        varchar(255),
    event_type   varchar(64)  not null,
    subject      varchar(255),
    action       varchar(128),
    resource     varchar(255),
    decision     varchar(16),               -- PERMIT | DENY | null (non-authz events)
    user_reason  text,                       -- #3: user-safe reason
    audit_reason text,                       -- #3: internal audit reason (must differ from user_reason on DENY)
    detail_json  jsonb,
    at           timestamptz  not null default now(),
    constraint audit_log_decision_ck check (decision is null or decision in ('PERMIT', 'DENY'))
);
create index audit_log_org_at_idx  on audit_log (org_id, at desc);
create index audit_log_subject_idx on audit_log (subject);

create or replace function audit_log_immutable() returns trigger
    language plpgsql as $$
begin
    raise exception 'audit_log is append-only (yaya-identity: no UPDATE/DELETE)';
end;
$$;

create trigger audit_log_no_mutate
    before update or delete on audit_log
    for each row execute function audit_log_immutable();

-- Transactional outbox: identity events (user.created, membership.added,
-- role.assigned, policy.changed, client.secret_rotated) written in the same tx
-- as the state change; a relay publishes them to consumers (I2+).
create table outbox (
    id           bigint generated by default as identity primary key,
    aggregate    varchar(64)  not null,
    aggregate_id varchar(64),
    event_type   varchar(64)  not null,
    payload_json jsonb        not null,
    status       varchar(16)  not null default 'PENDING',
    created_at   timestamptz  not null default now(),
    published_at timestamptz,
    constraint outbox_status_ck check (status in ('PENDING', 'PUBLISHED'))
);
create index outbox_pending_idx on outbox (created_at) where status = 'PENDING';

-- Idempotency store: a repeated (scope, key) returns the first stored response
-- so mutating admin/token calls are safe to retry (FR-7.3).
create table idempotency_keys (
    scope         varchar(64)  not null,
    idem_key      varchar(255) not null,
    response_json jsonb,
    created_at    timestamptz  not null default now(),
    primary key (scope, idem_key)
);
